/**
 * Lọc sạch toàn bộ đồ phụ nữ (Đầm, Chân váy, v.v.) nếu tài khoản là Nam
 */
export function sanitizeClothesForGender(items, gender) {
  const isMale = gender?.toLowerCase() === 'nam' || gender?.toLowerCase() === 'male';
  if (!isMale || !Array.isArray(items)) return items;

  const femaleKeywords = ['váy', 'đầm', 'croptop', 'tiểu thư', 'cao gót', 'chân váy', 'dress', 'skirt', 'heels', 'son phấn'];
  return items.filter(item => {
    if (!item) return false;
    if (item.categoryId === 3) return false;
    if (item.categoryName?.toLowerCase() === 'dresses') return false;

    const nameLower = (item.name || '').toLowerCase();
    const descLower = (item.description || '').toLowerCase();
    return !femaleKeywords.some(kw => nameLower.includes(kw) || descLower.includes(kw));
  });
}
